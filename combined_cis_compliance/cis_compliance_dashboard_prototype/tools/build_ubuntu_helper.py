"""Embed the Ubuntu setup files in the pairing helper, so one file sets a server up and then pairs it (task 9).

Usage (from the application directory), after any change to vm/ubuntu, the SCAP content or the install scripts:
    python -B -m tools.build_ubuntu_helper

The payload is the bundle template of tools/build_ubuntu_bundle.py (placeholders for the machine, hostname and
account left in), packed as a deterministic tar, compressed with xz and stored as base64 lines between two marker
lines in scripts/server_access/fyp-pair-ubuntu.py, with its SHA-256. The helper fills the placeholders on the server
from the machine itself and the account that ran sudo. Building runs nothing on any server; the same inputs always
give the same bytes, and a test fails while the committed helper is older than the code it would install.
"""
import base64
import hashlib
import io
import lzma
from pathlib import Path
import tarfile
import tempfile

APP = Path(__file__).resolve().parents[1]
HELPER = APP.parent / 'scripts' / 'server_access' / 'fyp-pair-ubuntu.py'
BEGIN = '# ---- Embedded setup payload: generated by tools/build_ubuntu_helper.py from the application files. Do not edit.'
END = '# ---- End of the embedded setup payload.'
LINE = 76


def payload():
    """The xz-compressed tar of the bundle template, byte for byte the same for the same inputs."""
    from tools.build_ubuntu_bundle import write_template
    with tempfile.TemporaryDirectory() as folder:
        root = write_template(Path(folder) / 'bundle')
        raw = io.BytesIO()
        with tarfile.open(fileobj=raw, mode='w', format=tarfile.USTAR_FORMAT) as archive:
            for path in sorted(root.rglob('*')):
                info = tarfile.TarInfo(path.relative_to(root).as_posix())
                info.mtime, info.uid, info.gid, info.uname, info.gname = 0, 0, 0, '', ''
                if path.is_dir():
                    info.type, info.mode = tarfile.DIRTYPE, 0o755
                    archive.addfile(info)
                else:
                    data = path.read_bytes()
                    info.size, info.mode = len(data), 0o644
                    archive.addfile(info, io.BytesIO(data))
    return lzma.compress(raw.getvalue(), preset=9)


def block(data):
    encoded = base64.b64encode(data).decode('ascii')
    lines = [encoded[i:i + LINE] for i in range(0, len(encoded), LINE)]
    return '\n'.join([BEGIN, f"PAYLOAD_SHA256 = '{hashlib.sha256(data).hexdigest()}'", 'PAYLOAD = ('] +
                     [f"    '{line}'," for line in lines] + [')', END])


def embed(text, data):
    """The helper's text with its payload block replaced (or added before the entry point the first time)."""
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        return head + block(data) + rest.split(END, 1)[1]
    marker = "\nif __name__ == '__main__':"
    head, tail = text.split(marker, 1)
    return head + '\n\n' + block(data) + '\n\n' + marker + tail


def main():
    data = payload()
    text = HELPER.read_bytes().decode('utf-8').replace('\r\n', '\n')
    HELPER.write_bytes(embed(text, data).encode('utf-8'))
    print(f'{HELPER}: payload {len(data)} bytes, SHA-256 {hashlib.sha256(data).hexdigest()}')


if __name__ == '__main__':
    main()
