"""Independent cross-check of the Ubuntu control results against OpenSCAP (task 17).

For each stored live scan and each control, compares two separately produced results:
  direct - this application's predicate over the direct effective-state probes, with the SCAP results removed;
  scap   - OpenSCAP's own verdict for the control's selected rules (ComplianceAsCode content, a separate engine).
Expected before any run: agreement, except the documented SSH explicit-line category (decision 2026-11-07: CIS
audits the effective `sshd -T` value; these SCAP rules also demand an explicit configuration line). Anything else
that disagrees is a finding to investigate, never silently accepted.

Reads temporary copies of the local store only. Usage (from the app directory):
  ..\\.venv-integration\\Scripts\\python.exe -B -m tools.scap_cross_check            # print markdown
  ..\\.venv-integration\\Scripts\\python.exe -B -m tools.scap_cross_check --write    # docs/evaluation/SCAP_CROSS_CHECK.md
"""
from collections import Counter
from pathlib import Path
import argparse
import json
import shutil
import sqlite3
import tempfile

APP = Path(__file__).resolve().parents[1]
DETERMINATE = ('Compliant', 'Non-Compliant')
SSH_EXPECTED = 'Expected disagreement (SSH explicit line)'
CIS_WORDING = 'Expected disagreement (CIS wording)'


def scap_verdict(results):
    """XCCDF-style aggregation of one control's selected rule results."""
    values = list(results.values())
    if 'fail' in values:
        return 'Non-Compliant'
    if values and all(v == 'notapplicable' for v in values):
        return 'Not applicable'
    if values and all(v in ('pass', 'notapplicable') for v in values):
        return 'Compliant'
    return 'Unresolved'


def compare(cid, observations):
    from backends.ubuntu.predicates import SSH, evaluate
    direct_obs = {k: v for k, v in observations.items() if k != 'scap_rules'}
    direct = evaluate(cid, direct_obs).status.value
    scap_obs = observations.get('scap_rules')
    scap = scap_verdict(scap_obs['value']) if scap_obs and scap_obs.get('state') == 'ok' else 'No SCAP result'
    if direct not in DETERMINATE or scap not in DETERMINATE:
        verdict = 'Not comparable'
    elif direct == scap:
        verdict = 'Agree'
    elif cid in SSH and direct == 'Compliant' and scap == 'Non-Compliant':
        verdict = SSH_EXPECTED
    elif direct == 'Compliant' and scap == 'Non-Compliant' and _only_reviewed_failures(cid, scap_obs['value']):
        verdict = CIS_WORDING
    else:
        verdict = 'Disagree'
    return {'control_id': cid, 'direct': direct, 'scap': scap, 'verdict': verdict}


def _only_reviewed_failures(cid, results):
    from backends.ubuntu.predicates import CIS_AUDIT_WORDING
    from vm.ubuntu.spec import SCAP_RULE_PREFIX
    failed = {rule[len(SCAP_RULE_PREFIX):] for rule, result in results.items() if result == 'fail'}
    return bool(failed) and failed <= set(CIS_AUDIT_WORDING.get(cid, {}))


def live_scans():
    """(collected_at, observations) for every stored live scan, from a temporary copy of the store."""
    folder = tempfile.mkdtemp()
    try:
        copy = Path(folder) / 'scans.sqlite3'
        shutil.copyfile(APP / 'data' / 'ubuntu' / 'integration_imports.sqlite3', copy)
        with sqlite3.connect(copy) as db:
            rows = db.execute("SELECT collected_at, raw FROM imported_assessments WHERE evidence_mode='Live (SSH)' "
                              'ORDER BY collected_at').fetchall()
        return [(at, json.loads(raw)['observations']) for at, raw in rows]
    finally:
        shutil.rmtree(folder, ignore_errors=True)


def order(cid):
    return [int(x) for x in cid.split('.')]


def markdown(scans):
    latest_at, latest = scans[-1]
    rows = [compare(cid, latest[cid]) for cid in sorted(latest, key=order)]
    history = Counter()
    for _, observations in scans:
        for cid in observations:
            history[(cid, compare(cid, observations[cid])['verdict'])] += 1
    totals = Counter(r['verdict'] for r in rows)
    disagreements = sorted({cid for (cid, verdict) in history if verdict == 'Disagree'}, key=order)
    lines = ['# Ubuntu independent cross-check against OpenSCAP', '',
             'Generated by `tools/scap_cross_check.py` from the stored live scans (temporary copy). For every control, '
             '**direct** is this application\'s predicate over the direct effective-state probes with the SCAP results '
             'removed; **scap** is OpenSCAP\'s own verdict for the control\'s selected ComplianceAsCode rules. Expected '
             'before the run: agreement, except the documented SSH explicit-line category.', '',
             '## Latest live scan (%s)' % latest_at, '',
             'Summary: ' + ', '.join('%s %d' % kv for kv in sorted(totals.items())), '',
             '| Control | Direct probes | OpenSCAP | Verdict |', '| --- | --- | --- | --- |']
    lines += ['| %s | %s | %s | %s |' % (r['control_id'], r['direct'], r['scap'],
                                        '**Disagree**' if r['verdict'] == 'Disagree' else r['verdict']) for r in rows]
    lines += ['', '## All %d stored live scans' % len(scans), '',
              'Controls that disagreed in any scan: ' + (', '.join(disagreements) or 'none'), '',
              '| Control | ' + ' | '.join(['Agree', SSH_EXPECTED, CIS_WORDING, 'Disagree', 'Not comparable']) + ' |',
              '| --- | --- | --- | --- | --- | --- |']
    for cid in sorted({c for c, _ in history}, key=order):
        lines.append('| %s | %s |' % (cid, ' | '.join(str(history[(cid, v)]) for v in
                                                      ('Agree', SSH_EXPECTED, CIS_WORDING, 'Disagree', 'Not comparable'))))
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true', help='write docs/evaluation/SCAP_CROSS_CHECK.md')
    args = parser.parse_args()
    text = markdown(live_scans())
    if args.write:
        (APP / 'docs' / 'evaluation' / 'SCAP_CROSS_CHECK.md').write_text(text, encoding='utf-8')
    print(text)


if __name__ == '__main__':
    main()
